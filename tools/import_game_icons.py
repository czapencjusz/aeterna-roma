"""Imports item icons from game-icons.net into the interface and writes CREDITS.md.

The icons are single-colour silhouettes licensed under CC BY 3.0 (see CREDITS.md).
To keep them in the game's hand-drawn style, the interface paints each one with the
same metal/wood/leather gradients, dark outline and sheen as the built-in art.

Usage (from the repository root):
    git clone --depth 1 https://github.com/game-icons/icons /tmp/game-icons
    python tools/import_game_icons.py /tmp/game-icons

It rewrites the block between the `<licensed-icons>` markers in aeterna/ui/index.html
and regenerates CREDITS.md. Edit ICONS below to add or change icons.
"""

