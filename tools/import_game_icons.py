def icon_paths(clone, source):
    with open(os.path.join(clone, source + '.svg'), encoding='utf-8') as f:
        svg = f.read()
    paths = [d for d in re.findall(r'<path[^>]*\sd="([^"]+)"', svg) if d != 'M0 0h512v512H0z']
    if not paths:
        raise SystemExit('No icon path found in %s' % source)
    return ' '.join(paths)


def main(clone):
    data = {}
    for key, source, material, look, _ in ICONS:
        author = source.split('/')[0]
        data[key] = {'d': icon_paths(clone, source), 'm': material, 'look': look, 'by': AUTHORS[author][0]}
    block = (START
             + '            // Item icons from game-icons.net (CC BY 3.0, see CREDITS.md), generated by\n'
             + '            // tools/import_game_icons.py. Painted in the game\'s style by licensedIcon() below.\n'
             + '            const LICENSED_ICONS = ' + json.dumps(data, separators=(',', ':')) + ';\n'
             + END)
    with open(PAGE, encoding='utf-8') as f:
        page = f.read()
    a, b = page.index(START), page.index(END) + len(END)
    with open(PAGE, 'w', encoding='utf-8') as f:
        f.write(page[:a] + block + page[b:])

    lines = ['# Credits', '',
             'All of the game\'s art is hand-drawn SVG made for Aeterna Roma, except the item icons below.', '',
             '## Item icons from [game-icons.net](https://game-icons.net)', '',
             'Licensed under [Creative Commons Attribution 3.0](https://creativecommons.org/licenses/by/3.0/).',
             'Changes: recoloured with the game\'s metal, wood and leather gradients, outlined, and given a sheen.', '',
             '| Icon | Author | Used for |', '|---|---|---|']
    for key, source, _, _, used_for in ICONS:
        author, name = source.split('/')
        label, site = AUTHORS[author]
        lines.append('| [%s](https://game-icons.net/1x1/%s/%s.html) | [%s](%s) | %s |'
                     % (name, author, name, label, site, used_for))
    with open(CREDITS, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines) + '\n')
    print('Imported %d icons; wrote %s' % (len(ICONS), os.path.relpath(CREDITS, ROOT)))


if __name__ == '__main__':
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    main(sys.argv[1])
